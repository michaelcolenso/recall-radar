#!/usr/bin/env node
// Extracts the @critical-marked regions from public/styles.css and writes
// src/templates/critical-css.ts for inlining in <head>.
// Usage: node scripts/build-critical-css.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const CRITICAL_REGION = /\/\* @critical:start \*\/([\s\S]*?)\/\* @critical:end \*\//g;

export function extractCriticalCss(cssText) {
  const regions = [];
  for (const match of cssText.matchAll(CRITICAL_REGION)) {
    regions.push(match[1]);
  }
  const compact = regions
    .join("\n")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/@font-face\s*\{[^}]*?(?:-ext\.woff2|font-style:\s*italic)[^}]*\}/g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,])\s*/g, "$1")
    .trim();
  // The full stylesheet retains every token. Inline only tokens referenced by
  // critical rules (including dependencies and dark-mode overrides).
  const roots = /(:root\{)([^{}]*)(\})/g;
  const needed = new Set([...compact.replace(roots, "").matchAll(/var\((--[\w-]+)/g)].map(match => match[1]));
  const declarations = [...compact.matchAll(roots)].flatMap(match => match[2].split(";"));
  let changed = true;
  while (changed) {
    changed = false;
    for (const declaration of declarations) {
      const [name, ...value] = declaration.split(":");
      if (!needed.has(name)) continue;
      for (const match of value.join(":").matchAll(/var\((--[\w-]+)/g)) {
        if (!needed.has(match[1])) { needed.add(match[1]); changed = true; }
      }
    }
  }
  return compact.replace(roots, (_, start, content, end) => start + content.split(";").filter(declaration => !declaration.startsWith("--") || needed.has(declaration.split(":")[0])).join(";") + end);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (isMain) {
  const root = path.resolve(fileURLToPath(import.meta.url), "../..");
  const cssPath = path.join(root, "public/styles.css");
  const outPath = path.join(root, "src/templates/critical-css.ts");

  const css = readFileSync(cssPath, "utf-8");
  const critical = extractCriticalCss(css);

  const output =
    `// AUTO-GENERATED by scripts/build-critical-css.mjs — DO NOT EDIT.\n` +
    `// Run \`npm run build:critical\` after editing the @critical regions in public/styles.css.\n` +
    `export const CRITICAL_CSS = ${JSON.stringify(critical)};\n`;

  writeFileSync(outPath, output);
  console.log(`Wrote ${critical.length} chars of critical CSS to ${path.relative(root, outPath)}`);
}
